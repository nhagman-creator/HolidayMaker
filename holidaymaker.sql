-- (I)      Checks if an existing database exists, if not a new HolidayMaker database will be created, overwrites old tables with new empty ones
-- (II)     Inserts mock-data according to the instructions found at:
--          https://mai26ma-ha.lms.nodehill.se/article/holiday-maker-individuell-projektuppgift-mai26

-- The mock-data consists of:
-- 1) 10 Hotels at 2 locations (Malmö/Sweden and Lund/Sweden)
-- 2) 40 rooms with at least 4 different capacities (max number of persons that can be accommodated), i.e. 1-4 persons
-- 3) 10 fictive customers
-- 4) 25 random bookings with durations and locations

-- Running th escript several times is safe, but the tables will be reset with original mock-values
-- To start a new clean database with empty tables, run part I of the code

-- PART I - create a new database with support of letters å-ä-ö, run remaining script within HolidayMaker DB, create or overwrite existing tables
CREATE DATABASE IF NOT EXISTS HolidayMaker CHARACTER SET utf8mb4;
USE HolidayMaker;
DROP TABLE IF EXISTS hotels_x_amenities, bookings, rooms, hotels, amenities, booking_statuses, customers;

CREATE TABLE customers (
    id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    address VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL,
    phone VARCHAR(20) NOT NULL
);

CREATE TABLE booking_statuses (
    id SMALLINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    status VARCHAR(30) NOT NULL,
    comment VARCHAR(255),
    CONSTRAINT uq_booking_statuses_status UNIQUE (status)
);

CREATE TABLE amenities (
    id SMALLINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    amenity VARCHAR(100) NOT NULL,
    CONSTRAINT uq_amenities_amenity UNIQUE (amenity)
);

CREATE TABLE hotels (
    id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    street VARCHAR(150) NOT NULL,
    postal VARCHAR(50) NOT NULL,
    municipality VARCHAR(100) NOT NULL,
    -- location VARCHAR(255) NOT NULL,
    dist_to_beach_m MEDIUMINT UNSIGNED NOT NULL,
    dist_to_city_center_m MEDIUMINT UNSIGNED NOT NULL,
    rating DECIMAL(2,1) NULL, -- explicitly stated here (default already Null)
    CONSTRAINT chk_hotels_rating CHECK (rating BETWEEN 0 and 5)
);

CREATE TABLE rooms (
    id SMALLINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    hotel_id INT UNSIGNED NOT NULL,
    room_number VARCHAR(10) NOT NULL,
    max_occupants TINYINT NOT NULL,
    price DECIMAL(10,2) NOT NULL,
    CONSTRAINT uq_rooms_hotel_room UNIQUE (hotel_id, room_number),
    CONSTRAINT chk_rooms_occupants CHECK (max_occupants > 0),
    CONSTRAINT chk_rooms_price CHECK (price >= 0),
    CONSTRAINT fk_rooms_hotel_id FOREIGN KEY (hotel_id) REFERENCES hotels (id)
);

CREATE TABLE bookings (
    booking_number BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    customer_id INT UNSIGNED NOT NULL,
    number_of_occupants TINYINT UNSIGNED NOT NULL,
    room_id SMALLINT UNSIGNED NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    status_id SMALLINT UNSIGNED NOT NULL,
    currency ENUM('SEK', 'EUR', 'USD') NOT NULL DEFAULT 'SEK',
    total_price DECIMAL(10,2) NOT NULL,
    CONSTRAINT fk_bookings_customer_id FOREIGN KEY (customer_id) REFERENCES customers (id),
    CONSTRAINT fk_bookings_room_id FOREIGN KEY (room_id) REFERENCES rooms (id),
    CONSTRAINT fk_bookings_status_id FOREIGN KEY (status_id) REFERENCES booking_statuses (id),
    CONSTRAINT chk_bookings_occupants CHECK (number_of_occupants > 0),
    CONSTRAINT chk_bookings_total_price CHECK (total_price >= 0),
    CONSTRAINT chk_bookings_dates CHECK (start_date < end_date), -- start date has to be less than end date
    CONSTRAINT chk_valid_period CHECK (start_date >= '2026-12-01' AND end_date <= '2026-12-31') -- valid booking period Dec-2026
);

CREATE TABLE hotels_x_amenities (
    hotel_id INT UNSIGNED NOT NULL,
    amenity_id SMALLINT UNSIGNED NOT NULL,
    PRIMARY KEY (hotel_id, amenity_id),
    CONSTRAINT fk_hotels_x_amenities_hotel_id FOREIGN KEY (hotel_id) REFERENCES hotels (id),
    CONSTRAINT fk_hotels_x_amenities_amenity_id FOREIGN KEY (amenity_id) REFERENCES amenities (id)
);

